print('Hello my dear "friend"!')
#printing double quotes inside a string using escape character
print("Hello my dear \"friend\"!")
#printing single quotes inside a string using double quotes
print("Hello my dear 'friend'!")
#printing single quotes inside a string using escape character
print('Hello my dear \'friend\'!')
#printing backslash inside a string using escape character
print("Hello my dear \\friend\\!")
#using f-strings for cleaner code
print(f"Hello my dear {name}!")
